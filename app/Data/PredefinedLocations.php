    /**
     * Get all cities for a given country.
     *
     * @param string $country
     * @return array<string>
     */
    public static function getCitiesByCountry(string $country): array
    {
        $allLocations = self::getAll();
        
        foreach ($allLocations as $continent => $countries) {
            if (isset($countries[$country])) {
                return $countries[$country];
            }
        }
        
        return [];
    }

    /**
     * Get all cities for a given continent.
     *
     * @param string $continent
     * @return array<string>
     */
    public static function getCitiesByContinent(string $continent): array
    {
        $allLocations = self::getAll();
        
        if (!isset($allLocations[$continent])) {
            return [];
        }
        
        $cities = [];
        foreach ($allLocations[$continent] as $country => $countryCities) {
            $cities = array_merge($cities, $countryCities);
        }
        
        return array_unique($cities);
    }

    /**
     * Get all countries for a given continent.
     *
     * @param string $continent
     * @return array<string>
     */
    public static function getCountriesByContinent(string $continent): array
    {
        $allLocations = self::getAll();
        
        if (!isset($allLocations[$continent])) {
            return [];
        }
        
        return array_keys($allLocations[$continent]);
    }

    /**
     * Check if a location exists in the predefined list.
     *
     * @param string $city
     * @param string|null $country
     * @param string|null $continent
     * @return array{continent: string|null, country: string|null, city: string|null}
     */
    public static function findLocation(string $city, ?string $country = null, ?string $continent = null): array
    {
        $allLocations = self::getAll();
        
        if ($continent && $country) {
            if (isset($allLocations[$continent][$country])) {
                if (in_array($city, $allLocations[$continent][$country], true)) {
                    return [
                        'continent' => $continent,
                        'country' => $country,
                        'city' => $city,
                    ];
                }
            }
        } elseif ($country) {
            foreach ($allLocations as $cont => $countries) {
                if (isset($countries[$country]) && in_array($city, $countries[$country], true)) {
                    return [
                        'continent' => $cont,
                        'country' => $country,
                        'city' => $city,
                    ];
                }
            }
        } else {
            foreach ($allLocations as $cont => $countries) {
                foreach ($countries as $coun => $cities) {
                    if (in_array($city, $cities, true)) {
                        return [
                            'continent' => $cont,
                            'country' => $coun,
                            'city' => $city,
                        ];
                    }
                }
            }
        }
        
        return [
            'continent' => null,
            'country' => null,
            'city' => null,
        ];
    }
